"""
Emits a real Diffusion Studio project (index.tsx) in the format confirmed
from editor/examples/01-basics.tsx: a <stage><scene><sequence> of <video>
elements with sequential start/end. This is the actual authoring surface
("the source is the document") -- rendering/exporting it for real still
needs `dapi open` against the running desktop app, which needs a display
(Xvfb) on this headless box and wasn't stood up this session.
"""
from pathlib import Path


def write_project(order: list, shots_dir: Path, durations: dict, out_dir: Path):
    out_dir.mkdir(parents=True, exist_ok=True)
    clips = []
    t = 0.0
    for f in order:
        dur = durations[f]
        clips.append(
            f'          <video src="{(shots_dir / f).as_posix()}" start={{{t:.3f}}} '
            f'end={{{t + dur:.3f}}} width={{1920}} height={{1080}} />'
        )
        t += dur

    tsx = f"""/* @jsxImportSource @diffusionstudio/jsx */
// Auto-generated by cardboard-eval-harness/harness/agent_greedy.py
// cp this file's directory into a project and run: dapi open <dir>

export default function Reassembly() {{
  return (
    <stage>
      <scene name="Reassembly" width={{1920}} height={{1080}} fill="black" active>
        <sequence name="A-roll">
{chr(10).join(clips)}
        </sequence>
      </scene>
    </stage>
  );
}}
"""
    (out_dir / "index.tsx").write_text(tsx)
